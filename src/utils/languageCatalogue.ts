export function getLanguageMetadata(localeCode: string): LanguageCatalogEntry {
  if (LANGUAGE_CATALOGUE[localeCode]) {
    return LANGUAGE_CATALOGUE[localeCode];
  }
  // Try matching prefix (e.g. 'hi' -> 'hi-IN')
  const prefix = localeCode.split('-')[0].toLowerCase();
  const matched = Object.values(LANGUAGE_CATALOGUE).find(
    (l) => l.iso639_1.toLowerCase() === prefix
  );
  return matched || LANGUAGE_CATALOGUE['en-US'];
}

export function isRtlLocale(localeCode: string): boolean {
  const meta = getLanguageMetadata(localeCode);
  return meta.direction === 'rtl';
}

export function getAvailableLanguagesList(): LanguageCatalogEntry[] {
  return Object.values(LANGUAGE_CATALOGUE);
}

export function getPublishedLanguagesList(): LanguageCatalogEntry[] {
  return Object.values(LANGUAGE_CATALOGUE).filter(
    (l) => l.status === 'published' || (l.status === 'beta' && l.isUiEnabled)
  );
}
