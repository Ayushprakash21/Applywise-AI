/**
 * Resolve translated string with parametric replacement and fallback to English
 */
export function translateKey(
  locale: string,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = DICTIONARIES[locale] || DICTIONARIES['en-US'];
  let text = dict[key] || DICTIONARIES['en-US']?.[key] || key;

  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`{{\\s*${pKey}\\s*}}`, 'g'), String(pVal));
    }
  }

  return text;
}
